import { Schema, model, type InferSchemaType } from 'mongoose';
import { geoPointSchema } from './common.js';
import { CATEGORIES, COMPLAINT_STATUSES, DUPLICATE_LINK_SOURCES, PRIORITIES, REVIEW_REASONS } from './enums.js';

export const PUBLIC_ID_PATTERN = /^CF-\d{4}-\d{5,}$/;

/** Citizen-facing status history. Internal notes belong in AuditLog / WorkOrder, not here. */
const statusEventSchema = new Schema(
  {
    status: { type: String, enum: COMPLAINT_STATUSES, required: true },
    at: { type: Date, required: true },
    publicNote: { type: String, trim: true, maxlength: 500 },
  },
  { _id: false },
);

/** Link from this complaint to the canonical complaint it duplicates. The original is never deleted. */
const duplicateLinkSchema = new Schema(
  {
    complaint: { type: Schema.Types.ObjectId, ref: 'Complaint', required: true },
    source: { type: String, enum: DUPLICATE_LINK_SOURCES, required: true },
    linkedBy: {
      type: Schema.Types.ObjectId,
      ref: 'User',
      required(this: { source?: string }) {
        return this.source === 'MANAGER';
      },
    },
    linkedAt: { type: Date, required: true },
    reason: { type: String, trim: true, maxlength: 500 },
  },
  { _id: false },
);

const complaintSchema = new Schema(
  {
    // Generated by the complaint service, e.g. CF-2026-00141.
    publicId: { type: String, required: true, trim: true, uppercase: true, match: PUBLIC_ID_PATTERN, immutable: true },
    citizen: { type: Schema.Types.ObjectId, ref: 'User', required: true, immutable: true },

    // Original report as written by the citizen. Kept unchanged.
    title: { type: String, required: true, trim: true, minlength: 5, maxlength: 120 },
    description: { type: String, required: true, trim: true, minlength: 10, maxlength: 2000 },
    location: { type: geoPointSchema, required: true },
    landmark: { type: String, trim: true, maxlength: 120 },
    selectedCategory: { type: String, enum: CATEGORIES },

    // Set only after validated classification or human review.
    confirmedCategory: { type: String, enum: CATEGORIES },
    department: { type: Schema.Types.ObjectId, ref: 'Department' },
    priority: { type: String, enum: PRIORITIES },

    status: { type: String, enum: COMPLAINT_STATUSES, required: true, default: 'REPORTED' },
    statusHistory: { type: [statusEventSchema], default: [] },
    rejectionReason: {
      type: String,
      trim: true,
      maxlength: 1000,
      required(this: { status?: string }) {
        return this.status === 'REJECTED';
      },
    },

    duplicateOf: { type: duplicateLinkSchema },

    // Latest automatic-routing evaluation. Present when the case needs a human routing decision.
    routingReview: {
      type: new Schema(
        {
          reasons: { type: [{ type: String, enum: REVIEW_REASONS }], default: [] },
          evaluatedAt: { type: Date, required: true },
          policyVersion: { type: String, required: true, maxlength: 40 },
        },
        { _id: false },
      ),
    },
    resolvedAt: { type: Date },
    closedAt: { type: Date },
  },
  { timestamps: true },
);

complaintSchema.pre('validate', function () {
  if (this.duplicateOf?.complaint && this._id && this.duplicateOf.complaint.equals(this._id)) {
    this.invalidate('duplicateOf.complaint', 'a complaint cannot be a duplicate of itself');
  }
});

complaintSchema.index({ publicId: 1 }, { unique: true });
complaintSchema.index({ citizen: 1, updatedAt: -1 }); // "My complaints"
complaintSchema.index({ department: 1, status: 1, createdAt: -1 }); // department queues
complaintSchema.index({ status: 1, createdAt: -1 }); // triage / admin views
complaintSchema.index({ confirmedCategory: 1, status: 1, createdAt: -1 });
complaintSchema.index({ location: '2dsphere' }); // nearby-duplicate search
complaintSchema.index({ 'duplicateOf.complaint': 1 }, { sparse: true }); // reports linked to a canonical issue
complaintSchema.index({ department: 1, resolvedAt: 1 }, { sparse: true }); // resolution-time metrics

export type ComplaintFields = InferSchemaType<typeof complaintSchema>;
export const Complaint = model('Complaint', complaintSchema);
